#!/usr/bin/env node
/**
 * Embeds openwebui/SYSTEM_PROMPT.md into openwebui/metrics_filter.py.
 *
 * The filter can inject the full prompt verbatim (INSTRUCTIONS=full) for deployments
 * that do not paste it into each model, but Open WebUI loads a function as a single
 * self-contained file — there is no way for the Python module to read the .md at
 * runtime. So the text has to be copied into the module, which means it can drift.
 *
 * This script is the only thing allowed to write that copy, and `npm test` fails if
 * the two disagree. Run `node scripts/sync-prompt.mjs --write` after editing the
 * prompt.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const FILTER_PATH = join(here, '..', 'openwebui', 'metrics_filter.py');
export const PROMPT_PATH = join(here, '..', 'openwebui', 'SYSTEM_PROMPT.md');

export const BEGIN = '# >>> SYSTEM_PROMPT (generated by scripts/sync-prompt.mjs — do not edit by hand)';
export const END = '# <<< SYSTEM_PROMPT';

/**
 * Replace the generated region of the filter with `promptText`.
 * JSON.stringify emits a double-quoted string with escaped newlines, which is also a
 * valid Python literal — so the prompt can contain any quotes or backslashes and the
 * module still parses. Docstrings were tempting and wrong: the prompt contains " and
 * a triple-quoted block would break the first time someone writes a quote at the end.
 */
export function renderFilter(source, promptText) {
  const start = source.indexOf(BEGIN);
  const stop = source.indexOf(END);
  if (start < 0 || stop < 0) throw new Error('generated region markers not found in filter');
  if (stop < start) throw new Error('generated region markers are in the wrong order');

  const block = `${BEGIN}\nFULL_INSTRUCTIONS = ${JSON.stringify(promptText)}\n${END}`;
  return source.slice(0, start) + block + source.slice(stop + END.length);
}

/** The prompt text as it should appear inside the filter, already normalised. */
export function expectedFilterText(promptText) {
  return renderFilter(readFileSync(FILTER_PATH, 'utf8'), promptText);
}

export function isInSync() {
  const prompt = readFileSync(PROMPT_PATH, 'utf8');
  const filter = readFileSync(FILTER_PATH, 'utf8');
  if (!filter.includes('FULL_INSTRUCTIONS')) throw new Error('filter has no FULL_INSTRUCTIONS');
  return renderFilter(filter, prompt) === filter;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const prompt = readFileSync(PROMPT_PATH, 'utf8');
  const filter = readFileSync(FILTER_PATH, 'utf8');
  const rendered = renderFilter(filter, prompt);

  if (process.argv.includes('--write')) {
    const changed = rendered !== filter;
    writeFileSync(FILTER_PATH, rendered);
    console.log(
      changed
        ? `embedded ${prompt.length} chars from SYSTEM_PROMPT.md into metrics_filter.py`
        : 'filter already in sync; nothing to write',
    );
  } else if (rendered !== filter) {
    console.error('openwebui/metrics_filter.py is out of date with SYSTEM_PROMPT.md');
    console.error('run: node scripts/sync-prompt.mjs --write');
    process.exit(1);
  } else {
    console.log('filter instructions in sync with SYSTEM_PROMPT.md');
  }
}
